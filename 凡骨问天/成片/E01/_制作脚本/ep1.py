def tts_lines():
    """返回配音任务列表：(镜号, 角色, 台词, 情绪, 语速, 音高, 音色, 音频ID)
    音频ID = E01_Sxx_角色；同镜同角色多句时追加 _2/_3，避免文件名互相覆盖。"""
    out = []
    counters = {}
    for no, dur, size, move, refs, img, vid, subs in SHOTS:
        for who, text in subs:
            if who in ("字幕", "片尾", "取景"):
                continue
            vid_, sp, pi = VOICES.get(who, (None, 1.0, 0))
            emo = EMOTION.get((who, text), "neutral")
            base = "E01_S%02d_%s" % (no, who)
            counters[base] = counters.get(base, 0) + 1
            fid = base if counters[base] == 1 else "%s_%d" % (base, counters[base])
            out.append((no, who, text, emo, sp, pi, vid_, fid))
    return out


